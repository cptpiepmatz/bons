import { assert } from "@std/assert";
import { Node, Project } from "ts-morph";

type Labels = Record<"en" | "de", string>;

export function generateCategories(binding: string): string {
  const project = new Project({ useInMemoryFileSystem: true });
  const source = project.createSourceFile("Category.ts", binding);
  const category = source.getTypeAliasOrThrow("Category");
  const type = category.getTypeNodeOrThrow();
  const members = Node.isUnionTypeNode(type) ? type.getTypeNodes() : [type];
  const ids = members.map((member) => {
    assert(
      Node.isLiteralTypeNode(member),
      "Category must contain only string literals",
    );
    const literal = member.getLiteral();
    assert(
      Node.isStringLiteral(literal),
      "Category must contain only string literals",
    );
    return literal.getLiteralValue();
  });
  const labels = new Map<string, Labels>();

  for (const doc of category.getJsDocs()) {
    for (const tag of doc.getTags()) {
      if (tag.getTagName() !== "category") continue;
      const match = tag.getCommentText()?.trim().match(/^(\S+)\s+(\{.*\})$/);
      assert(match, 'Expected @category <id> { "en": "...", "de": "..." }');
      const [, id, json] = match;
      assert(ids.includes(id), `Unknown category label: ${id}`);
      assert(!labels.has(id), `Duplicate category label: ${id}`);
      const value: unknown = JSON.parse(json);
      assert(
        typeof value === "object" && value !== null &&
          "en" in value && typeof value.en === "string" && value.en.trim() &&
          "de" in value && typeof value.de === "string" && value.de.trim(),
        `Category ${id} requires non-empty en and de labels`,
      );
      labels.set(id, { en: value.en, de: value.de });
    }
  }

  const entries = ids.map((id) => {
    const label = labels.get(id);
    assert(label, `Missing category labels: ${id}`);
    const labelJson = JSON.stringify(label, null, 2).replaceAll(/\n\s*/g, " ");
    return `  ${JSON.stringify(id)}: ${labelJson},`;
  });

  return [
    `// Generated by tools/generate_categories.ts.`,
    `// Do not edit manually.`,
    ``,
    `import type { Category } from "../../bindings/Category.ts";`,
    ``,
    `export const categories = {`,
    ...entries,
    `} as const satisfies Record<Category, Record<"en" | "de", string>>;`,
  ].join("\n");
}

if (import.meta.main) {
  const binding = await Deno.readTextFile(
    new URL("../bindings/Category.ts", import.meta.url),
  );
  const output = new URL("../frontend/generated/", import.meta.url);
  const generated = generateCategories(binding);
  await Deno.mkdir(output, { recursive: true });
  await Deno.writeTextFile(new URL("categories.ts", output), generated);
}
